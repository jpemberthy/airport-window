// Authoring only: reproduce the MDE drawing scaffold and pack registration.
// Geographic inputs: OpenStreetMap contributors, ODbL-1.0; see MAP.md.
import { readFileSync, writeFileSync } from 'node:fs';
const root = new URL('../../', import.meta.url);
const { ways } = JSON.parse(
  readFileSync(new URL('public/data/mde-map.json', root), 'utf8'),
);
const origin = { lon: -75.425, lat: 6.1645 };
const projection = {
  a: 0.6,
  b: 0.8,
  c: 0.52,
  d: -0.39,
  scale: 0.38,
  width: 1672,
  height: 941,
};
const project = ([lon, lat]) => {
  const east =
    (lon - origin.lon) * 111320 * Math.cos((6.164461 * Math.PI) / 180);
  const north = (lat - origin.lat) * 111320;
  return [
    836 + (projection.a * east + projection.b * north) * projection.scale,
    470.5 + (projection.c * east + projection.d * north) * projection.scale,
  ];
};
const line = (coordinates) =>
  coordinates
    .map((p) =>
      project(p)
        .map((n) => n.toFixed(3))
        .join(','),
    )
    .join(' ');
const svg = [
  '<svg xmlns="http://www.w3.org/2000/svg" width="1672" height="941" viewBox="0 0 1672 941">',
  '<rect width="1672" height="941" fill="#8eb378"/>',
];
const polygon = (w, fill, stroke = fill) =>
  svg.push(
    `<polygon points="${line(w.coordinates)}" fill="${fill}" stroke="${stroke}" stroke-width="1"/>`,
  );
const stroke = (w, color, width, extras = '') =>
  svg.push(
    `<polyline points="${line(w.coordinates)}" fill="none" stroke="${color}" stroke-width="${width}" stroke-linejoin="round" ${extras}/>`,
  );
for (const w of ways) {
  if (w.tags.landuse === 'forest' || w.tags.natural === 'wood')
    polygon(w, '#527f54');
  else if (w.tags.landuse === 'farmland' || w.tags.landuse === 'meadow')
    polygon(w, '#a4bd78');
  else if (w.tags.landuse === 'residential') polygon(w, '#b6bb8c');
  else if (w.tags.leisure) polygon(w, '#76a66b');
  if (w.tags.natural === 'water') polygon(w, '#659d9c');
}
for (const w of ways) if (w.tags.aeroway === 'aerodrome') polygon(w, '#a2b97c');
for (const w of ways)
  if (
    w.tags.highway &&
    !['footway', 'path', 'steps', 'cycleway'].includes(w.tags.highway)
  ) {
    const major = ['motorway', 'trunk', 'primary', 'secondary'].includes(
      w.tags.highway,
    );
    stroke(w, '#748175', major ? 6 : 3);
    stroke(w, '#d2c8ac', major ? 4 : 1.5);
  }
for (const w of ways)
  if (w.tags.building && w.tags.building !== 'no')
    polygon(w, '#d4bea0', '#888774');
for (const w of ways)
  if (w.tags.aeroway === 'apron') polygon(w, '#c6c3ac', '#989b8b');
for (const w of ways)
  if (['taxiway', 'taxilane'].includes(w.tags.aeroway)) {
    stroke(w, '#7d8682', w.tags.aeroway === 'taxiway' ? 9 : 5);
    stroke(w, '#e8d887', 0.8);
  }
for (const w of ways)
  if (['terminal', 'hangar'].includes(w.tags.aeroway))
    polygon(w, '#9cb7c3', '#587a88');
for (const w of ways)
  if (w.tags.aeroway === 'jet_bridge') stroke(w, '#bbc6c5', 2.5);
for (const w of ways)
  if (w.tags.aeroway === 'runway') {
    stroke(w, '#303b43', 19);
    stroke(w, '#ebe9d8', 1.3, 'stroke-dasharray="11 11"');
  }
svg.push('</svg>');
writeFileSync(
  new URL('public/airports/mde/map/guide.svg', root),
  svg.join('\n') + '\n',
);
const runway = ways.find(
  (w) => w.id === '35826614' && w.tags.aeroway === 'runway',
);
if (!runway) throw new Error('Missing MDE runway source');
const round = (p) => p.map((n) => Number(n.toFixed(3)));
const map = {
  label: 'Airport map',
  shortLabel: 'Map',
  width: 1672,
  height: 941,
  origin,
  projection,
  stationaryAnchors: [
    [0, 0],
    [1672, 0],
    [1672, 941],
    [0, 941],
    [100, 470],
    [1570, 470],
    [836, 100],
    [836, 850],
  ],
  runways: [
    {
      name: '01/19',
      start: runway.coordinates[0],
      end: runway.coordinates.at(-1),
      artStart: round(project(runway.coordinates[0])),
      artEnd: round(project(runway.coordinates.at(-1))),
    },
  ],
  taxiLanes: ways
    .filter((w) => ['taxiway', 'taxilane'].includes(w.tags.aeroway))
    .map((w) => ({
      id: `osm-${w.id}`,
      points: w.coordinates.map((p) => round(project(p))),
    })),
  assets: {
    day: '/airports/mde/map/day.webp',
    night: '/airports/mde/map/night.webp',
    aircraft: '/art/harbor/aircraft.webp',
  },
};
writeFileSync(
  new URL('airports/mde/map.ts', root),
  "// Generated by generate-map.mjs. OpenStreetMap contributors, ODbL-1.0; see MAP.md.\nimport type { AirportMap } from '../types';\nexport const mdeMap: AirportMap = " +
    JSON.stringify(map, null, 2) +
    ';\n',
);
console.log(
  JSON.stringify(
    { runway: map.runways[0], taxiLanes: map.taxiLanes.length },
    null,
    2,
  ),
);
